"""Разбор текста ячейки (таблица cell_text из §11 АРХИТЕКТУРА.md)."""

import pytest

from schedule_parser.cell_text import parse

CASES = [
    # вход, предмет, преподаватель, аудитория
    ("Аккаунтинг и аудит Батаева П.С.2-05", "Аккаунтинг и аудит", "Батаева П.С.", "2-05"),
    (
        "Администрирование в инфокоммуникационных системах Базаев А.А",
        "Администрирование в инфокоммуникационных системах", "Базаев А.А", None,
    ),
    (
        "Проектирование программного обеспечения Аюбов. С-М. 3-08",
        "Проектирование программного обеспечения", "Аюбов. С-М.", "3-08",
    ),
    (
        "Программирование на Python Умархаджиев М-Х.Р. 3-08",
        "Программирование на Python", "Умархаджиев М-Х.Р.", "3-08",
    ),
    ("Правоведение Азиева П.З. читальный зал (1 этаж)", "Правоведение", "Азиева П.З.", "читальный зал (1 этаж)"),
    (
        "Физическая культура и спорт (юноши) Навурбиев А.В. 3 корпус",
        "Физическая культура и спорт", "Навурбиев А.В.", "3 корпус",
    ),
    # Дополнительные случаи из реального файла
    ("Введение в специальность Мальсагов Б.С 2-23", "Введение в специальность", "Мальсагов Б.С", "2-23"),
    ("Информатика Абубакаров М. 3-12", "Информатика", "Абубакаров М.", "3-12"),
    ("Теория связи Аюбов С-М. 2-21", "Теория связи", "Аюбов С-М.", "2-21"),
    ("Технологическое предпринимательство Халиев М.С-У. 2-05", "Технологическое предпринимательство", "Халиев М.С-У.", "2-05"),
]


@pytest.mark.parametrize("raw, subject, teacher, room", CASES)
def test_parse(raw: str, subject: str, teacher: str | None, room: str | None) -> None:
    parsed = parse(raw)
    assert parsed.subject == subject
    assert parsed.teacher == teacher
    assert parsed.room == room


def test_pe_tags() -> None:
    assert parse("Физическая культура и спорт (юноши) Навурбиев А.В. 3 корпус").tags == ["male"]
    assert parse("Физическая культура и спорт (девушки) Магомадова Я.Г. 3 корпус").tags == ["female"]
    assert parse("Философия Кутаев А.Х. 3-01").tags == []


def test_subject_fixes() -> None:
    fixes = {"Аккаутинг": "Аккаунтинг"}
    parsed = parse("Аккаутинг и аудит Батаева П.С. 2-13", fixes)
    assert parsed.subject == "Аккаунтинг и аудит"


def test_unrecognized_text_keeps_raw_as_subject() -> None:
    parsed = parse("Батаева П.С.")
    assert parsed.teacher == "Батаева П.С."
    assert parsed.subject == "Батаева П.С."  # предмет пустой → берём исходный текст


def test_teacher_typo_fix_from_config() -> None:
    """Опечатка в инициалах из config.json (subjectFixes) исправляется и в фамилии преподавателя."""
    fixes = {"Батукаева А.С.": "Батукаева А.Р."}
    parsed = parse("Правоведение Батукаева А.С. 3-08", fixes)
    assert parsed.teacher == "Батукаева А.Р."
    assert parsed.room == "3-08"
    # другой преподаватель не затрагивается
    assert parse("Правоведение Азиева П.З. 3-08", fixes).teacher == "Азиева П.З."

