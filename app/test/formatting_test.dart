// Подписи для экранной читалки и мелкие помощники форматирования.

import 'package:flutter_test/flutter_test.dart';
import 'package:unigraf/core/formatting.dart';

void main() {
  group('joinSentences: без двойной точки', () {
    test('обычная подпись: предложения через точку', () {
      expect(joinSentences('Философия, лекция, 2-05', ['Есть домашнее задание', 'Перенесено']), 'Философия, лекция, 2-05. Есть домашнее задание. Перенесено');
    });
    test('если фраза уже кончается точкой (инициалы), вторая точка не добавляется', () {
      expect(joinSentences('Философия, Кутаев А.Х.', ['Вместе с группами: 1 БИ-25']), 'Философия, Кутаев А.Х. Вместе с группами: 1 БИ-25');
    });
    test('без продолжения подпись не меняется', () {
      expect(joinSentences('Философия', const []), 'Философия');
    });
  });
}
